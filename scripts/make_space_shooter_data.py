"""Generate space-shooter/data.js -- the wave plan for the shooter game.

The game is the only interactive thing in this repo, and it is data-driven for
the same reason the SVGs are: it must never disagree with the heatmap. One month
of data/contributions.json becomes one wave, and every contribution day in that
month becomes exactly one enemy block carrying that day's real count and
heatmap level. A month with no contributions produces a quiet wave with no
blocks at all, so a sparse month still plays as a breather rather than as a lie.

The output is a JS assignment rather than JSON so the site is standalone: it
opens from GitHub Pages, from a local file:// or from the repo folder with no
fetch and no server, which is also why nothing here depends on a build step.

Run: python scripts/make_space_shooter_data.py   # writes space-shooter/data.js
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
DATA = REPO / "data" / "contributions.json"
OUT = REPO / "space-shooter" / "data.js"

MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
          "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def wave_for(month: str, days: list[dict]) -> dict:
    """One month of contribution days as a spawn list.

    Days are emitted in calendar order so the game can lay them out in reading
    order (the same order the heatmap is read), and `busiest` scales the wave's
    block sizes from the month's own peak day rather than a global peak.
    """
    hits = [d for d in days if d["count"] > 0]
    return {
        "label": f"{MONTHS[int(month[5:7]) - 1]} {month[:4]}",
        "month": month,
        "total": sum(d["count"] for d in hits),
        "busiest": max((d["count"] for d in hits), default=0),
        "days": [
            {
                "count": d["count"],
                "level": d["level"],
                "weekday": d["weekday"],
                "date": d["date"],
            }
            for d in hits
        ],
    }


def build() -> dict:
    payload = json.loads(DATA.read_text(encoding="utf-8"))
    stats = payload.get("stats", {})
    days = payload.get("days", [])

    by_month: dict[str, list[dict]] = defaultdict(list)
    for day in days:
        by_month[day["date"][:7]].append(day)

    waves = [
        wave_for(month, by_month[month]) for month in sorted(by_month)
    ]

    return {
        "generated_at": payload.get("generated_at", ""),
        "username": payload.get("username", ""),
        "total": stats.get("total_last_year", 0),
        "active_days": stats.get("active_days", 0),
        "best_day": stats.get("best_day", {"date": "", "count": 0}),
        "longest_streak": stats.get("longest_streak", 0),
        "waves": waves,
    }


def main() -> None:
    data = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    # JSON first, then a JS wrapper: the body stays valid JSON if the
    # "window.SHOOTER_DATA = " prefix and the trailing ";" are removed.
    body = json.dumps(data, indent=1)
    lines = [
        "// Generated by scripts/make_space_shooter_data.py from "
        "data/contributions.json -- do not edit by hand.",
        "// The daily profile-art workflow refreshes it with the rest of the art.",
        "// A plain assignment, not a fetch, so the site runs from GitHub Pages,",
        "// from the repo folder, or from file:// with no server.",
        "window.SHOOTER_DATA = " + body + ";",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    months = len(data["waves"])
    blocks = sum(len(w["days"]) for w in data["waves"])
    print(
        f"[shooter] wrote {OUT} ({months} waves, {blocks} blocks, "
        f"total {data['total']})"
    )


if __name__ == "__main__":
    main()
